function applyStaticTranslations() {
  const lang = LANGUAGES[currentLang];
  document.documentElement.lang = currentLang === "zh" ? "zh-CN" : currentLang === "ja" ? "ja" : "en";
  document.title = lang.title;

  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.dataset.i18n;
    const value = lang[key];
    if (typeof value === "string") el.textContent = value;
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    const key = el.dataset.i18nPlaceholder;
    const value = lang[key];
    if (typeof value === "string") el.setAttribute("placeholder", value);
  });

  document.querySelectorAll('input[name="language"]').forEach(el => {
    el.checked = el.value === currentLang;
  });
}

function setLanguage(lang) {
  if (!LANGUAGES[lang]) return;
  currentLang = lang;
  localStorage.setItem("utau_reclist_lang", lang);
  applyStaticTranslations();
}
